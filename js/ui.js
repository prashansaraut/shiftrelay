export function icons() {
  if (window.lucide?.createIcons) {
    window.lucide.createIcons();
    return;
  }
  // Offline fallback
  $$('i[data-lucide]').forEach(el => {
    const name = el.getAttribute('data-lucide');
    const content = SVG_MAP[name];
    if (content) {
      el.outerHTML = `<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-${name}" style="display:inline-block;vertical-align:middle;">${content}</svg>`;
    }
  });
}

export const ask = (msg, input) => new Promise(res => {
  const d = document.createElement('dialog');
  d.innerHTML = `<form method="dialog"><p>${esc(msg)}</p>${input ? '<textarea name="v" rows="3"></textarea>' : ''}<div class="row end"><button value="no" formnovalidate class="btn">Cancel</button><button value="yes" class="btn primary">Confirm</button></div></form>`;
  d.onclose = () => {
    const ok = d.returnValue === 'yes', v = d.querySelector('textarea')?.value.trim();
    d.remove();
    res(ok ? (input ? v || false : true) : false);
  };
  document.body.append(d);
  d.showModal();
});
